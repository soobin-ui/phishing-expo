def T(msg, hint, gave=None, **extra):
    t = {'message': msg, 'hint': hint}
    if gave:
        t['gave'] = gave
    t.update(extra)
    return t


def F(target, match, label, explain, probe=None):
    f = {'target': target, 'match': match, 'label': label, 'explain': explain}
    if probe:
        f['probe'] = probe
    return f


def P(question, *options):
    '''수상한 곳을 찾은 뒤 "어떻게 조사할까요?" 말풍선.
    options 는 (문구, 정답여부, 이유) 세 쌍입니다. 정답은 하나여야 합니다.
    ★ 오답도 그럴듯해야 합니다. 뻔한 오답을 넣으면 고르는 재미가 없습니다.'''
    opts = [{'label': o[0], 'ok': o[1], 'why': o[2]} for o in options]
    assert sum(1 for o in opts if o['ok']) == 1, question
    return {'question': question, 'options': opts}


